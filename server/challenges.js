// Versión que se envía al navegador: sin los tests ocultos.
export function publicChallenge(c) {
  const visible = c.tests.filter((x) => !x.hidden);
  return {
    id: c.id,
    title: c.title,
    difficulty: c.difficulty,
    category: c.category,
    fn: c.fn,
    pyFn: c.pyFn,
    params: c.params,
    returns: c.returns,
    pyReturns: c.pyReturns,
    description: c.description,
    hints: c.hints,
    xp: c.xp,
    examples: visible.map(({ args, expected }) => ({ args, expected })),
    totalTests: c.tests.length,
  };
}
