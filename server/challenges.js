export const toSnake = (name) =>
  name.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/([A-Z])([A-Z][a-z])/g, '$1_$2').toLowerCase();

function hanoiMoves(n, from, to, via) {
  if (n === 0) return [];
  return [...hanoiMoves(n - 1, from, via, to), `${from}->${to}`, ...hanoiMoves(n - 1, via, to, from)];
}

